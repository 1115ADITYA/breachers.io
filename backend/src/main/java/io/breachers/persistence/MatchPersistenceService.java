package io.breachers.persistence;

import jakarta.annotation.PostConstruct;
import jakarta.annotation.PreDestroy;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Service;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.*;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

/**
 * MatchPersistenceService
 * Academic demonstration of robust Java JDBC persistence for Breachers.io.
 * Handles server-authoritative match summaries and player career statistics
 * using Spring's JdbcTemplate with parameterized SQL queries and non-blocking asynchronous execution.
 */
@Service
public class MatchPersistenceService {

    private static final Logger log = LoggerFactory.getLogger(MatchPersistenceService.class);

    private final JdbcTemplate jdbcTemplate;
    private final ExecutorService persistenceExecutor;

    public MatchPersistenceService(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
        this.persistenceExecutor = Executors.newSingleThreadExecutor(r -> {
            Thread t = new Thread(r, "breachers-jdbc-worker");
            t.setDaemon(true);
            return t;
        });
    }

    @PostConstruct
    public void initSchema() {
        try {
            log.info("Verifying Breachers.io JDBC database schema...");
            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS match_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    room_code VARCHAR(16) NOT NULL,
                    game_mode VARCHAR(16) NOT NULL,
                    map_id VARCHAR(32) NOT NULL,
                    winner VARCHAR(64) NOT NULL,
                    red_score INT DEFAULT 0,
                    blue_score INT DEFAULT 0,
                    player_count INT DEFAULT 0,
                    end_reason VARCHAR(128),
                    duration_seconds INT DEFAULT 0,
                    completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """);

            jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS player_statistics (
                    username VARCHAR(64) PRIMARY KEY,
                    matches_played INT DEFAULT 0,
                    wins INT DEFAULT 0,
                    losses INT DEFAULT 0,
                    kills INT DEFAULT 0,
                    deaths INT DEFAULT 0,
                    score INT DEFAULT 0,
                    last_played_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """);

            Integer matchCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM match_history", Integer.class);
            if (matchCount == null || matchCount == 0) {
                log.info("Seeding academic baseline match records for evaluation...");
                recordMatch(new MatchRecord(
                        "ALPHA1",
                        "TDM",
                        "warehouse",
                        "RED",
                        25,
                        19,
                        4,
                        "Kill limit reached",
                        185,
                        LocalDateTime.now().minusMinutes(12),
                        List.of(
                                new MatchRecord.PlayerResult("Vanguard_01", "RED", 14, 8, 1250, true),
                                new MatchRecord.PlayerResult("Ghost_Spectre", "BLUE", 11, 10, 950, false),
                                new MatchRecord.PlayerResult("Stryker_Recon", "RED", 11, 11, 875, true),
                                new MatchRecord.PlayerResult("Enforcer_Tank", "BLUE", 8, 14, 600, false)
                        )
                ));
            }
            log.info("JDBC schema initialization verified successfully.");
        } catch (DataAccessException e) {
            log.error("Failed to initialize JDBC database schema:", e);
        }
    }

    @PreDestroy
    public void shutdown() {
        persistenceExecutor.shutdown();
        try {
            if (!persistenceExecutor.awaitTermination(3, TimeUnit.SECONDS)) {
                persistenceExecutor.shutdownNow();
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }

    /**
     * Non-blocking asynchronous submission to persist match record.
     * Prevents real-time WebSocket tick delays from database latency or failures.
     */
    public void recordMatchAsync(MatchRecord record) {
        if (record == null) return;
        persistenceExecutor.submit(() -> {
            try {
                recordMatch(record);
            } catch (Exception e) {
                log.error("Error in asynchronous match persistence for room {}: {}", record.roomCode(), e.getMessage(), e);
            }
        });
    }

    /**
     * Authoritative synchronous JDBC persistence using parameterized SQL queries.
     */
    public void recordMatch(MatchRecord record) {
        if (record == null) return;

        LocalDateTime completedAt = record.completedAt() != null ? record.completedAt() : LocalDateTime.now();
        Timestamp timestamp = Timestamp.valueOf(completedAt);

        // 1. Insert Match Record into match_history
        String insertMatchSql = """
            INSERT INTO match_history (
                room_code, game_mode, map_id, winner,
                red_score, blue_score, player_count,
                end_reason, duration_seconds, completed_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """;

        jdbcTemplate.update(
                insertMatchSql,
                record.roomCode(),
                record.gameMode(),
                record.mapId(),
                record.winner(),
                record.redScore(),
                record.blueScore(),
                record.playerCount(),
                record.endReason(),
                record.durationSeconds(),
                timestamp
        );

        log.info("Persisted match summary to JDBC match_history: room={}, winner={}", record.roomCode(), record.winner());

        // 2. Upsert Player Career Statistics
        if (record.playerResults() != null) {
            for (MatchRecord.PlayerResult player : record.playerResults()) {
                if (player.username() == null || player.username().isBlank()) continue;
                upsertPlayerStats(player, timestamp);
            }
        }
    }

    private void upsertPlayerStats(MatchRecord.PlayerResult player, Timestamp timestamp) {
        String checkSql = "SELECT COUNT(*) FROM player_statistics WHERE username = ?";
        Integer count = jdbcTemplate.queryForObject(checkSql, Integer.class, player.username());

        int winInc = player.won() ? 1 : 0;
        int lossInc = player.won() ? 0 : 1;

        if (count != null && count > 0) {
            String updateSql = """
                UPDATE player_statistics
                SET matches_played = matches_played + 1,
                    wins = wins + ?,
                    losses = losses + ?,
                    kills = kills + ?,
                    deaths = deaths + ?,
                    score = score + ?,
                    last_played_at = ?
                WHERE username = ?
            """;
            jdbcTemplate.update(
                    updateSql,
                    winInc,
                    lossInc,
                    player.kills(),
                    player.deaths(),
                    player.score(),
                    timestamp,
                    player.username()
            );
        } else {
            String insertSql = """
                INSERT INTO player_statistics (
                    username, matches_played, wins, losses,
                    kills, deaths, score, last_played_at
                ) VALUES (?, 1, ?, ?, ?, ?, ?, ?)
            """;
            jdbcTemplate.update(
                    insertSql,
                    player.username(),
                    winInc,
                    lossInc,
                    player.kills(),
                    player.deaths(),
                    player.score(),
                    timestamp
            );
        }
    }

    /**
     * Retrieve recent match history using parameterized LIMIT query.
     */
    public List<MatchSummary> getRecentMatches(int limit) {
        String sql = """
            SELECT id, room_code, game_mode, map_id, winner,
                   red_score, blue_score, player_count,
                   end_reason, duration_seconds, completed_at
            FROM match_history
            ORDER BY completed_at DESC, id DESC
            LIMIT ?
        """;

        return jdbcTemplate.query(sql, new MatchSummaryRowMapper(), Math.max(1, limit));
    }

    /**
     * Retrieve top players sorted by career score and kills.
     */
    public List<PlayerStats> getTopPlayers(int limit) {
        String sql = """
            SELECT username, matches_played, wins, losses, kills, deaths, score, last_played_at
            FROM player_statistics
            ORDER BY score DESC, kills DESC
            LIMIT ?
        """;

        return jdbcTemplate.query(sql, new PlayerStatsRowMapper(), Math.max(1, limit));
    }

    /**
     * Retrieve individual operator career statistics.
     */
    public Optional<PlayerStats> getPlayerStats(String username) {
        String sql = """
            SELECT username, matches_played, wins, losses, kills, deaths, score, last_played_at
            FROM player_statistics
            WHERE username = ?
        """;

        List<PlayerStats> results = jdbcTemplate.query(sql, new PlayerStatsRowMapper(), username);
        return results.isEmpty() ? Optional.empty() : Optional.of(results.getFirst());
    }

    /**
     * Aggregate global metrics for academic reporting.
     */
    public Map<String, Object> getGlobalStats() {
        Map<String, Object> stats = new LinkedHashMap<>();

        Integer totalMatches = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM match_history", Integer.class);
        Integer totalPlayers = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM player_statistics", Integer.class);
        Integer totalKills = jdbcTemplate.queryForObject(
                "SELECT COALESCE(SUM(kills), 0) FROM player_statistics", Integer.class);

        stats.put("totalMatches", totalMatches != null ? totalMatches : 0);
        stats.put("registeredOperators", totalPlayers != null ? totalPlayers : 0);
        stats.put("totalCombatKills", totalKills != null ? totalKills : 0);
        stats.put("databaseEngine", "H2 In-Memory JDBC");
        stats.put("systemTime", LocalDateTime.now().toString());

        return stats;
    }

    /**
     * Demonstrates pure raw JDBC database querying using java.sql.Connection,
     * java.sql.PreparedStatement, and java.sql.ResultSet.
     */
    public List<Map<String, Object>> executeRawJdbcQuery(String sql, Object... params) throws SQLException {
        List<Map<String, Object>> results = new ArrayList<>();
        if (jdbcTemplate.getDataSource() == null) return results;

        try (java.sql.Connection conn = jdbcTemplate.getDataSource().getConnection();
             java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {
            for (int i = 0; i < params.length; i++) {
                stmt.setObject(i + 1, params[i]);
            }
            try (java.sql.ResultSet rs = stmt.executeQuery()) {
                java.sql.ResultSetMetaData meta = rs.getMetaData();
                int colCount = meta.getColumnCount();
                while (rs.next()) {
                    Map<String, Object> row = new LinkedHashMap<>();
                    for (int c = 1; c <= colCount; c++) {
                        row.put(meta.getColumnLabel(c), rs.getObject(c));
                    }
                    results.add(row);
                }
            }
        }
        return results;
    }

    private static class MatchSummaryRowMapper implements RowMapper<MatchSummary> {
        @Override
        public MatchSummary mapRow(ResultSet rs, int rowNum) throws SQLException {
            Timestamp ts = rs.getTimestamp("completed_at");
            LocalDateTime completedAt = ts != null ? ts.toLocalDateTime() : null;

            return new MatchSummary(
                    rs.getLong("id"),
                    rs.getString("room_code"),
                    rs.getString("game_mode"),
                    rs.getString("map_id"),
                    rs.getString("winner"),
                    rs.getInt("red_score"),
                    rs.getInt("blue_score"),
                    rs.getInt("player_count"),
                    rs.getString("end_reason"),
                    rs.getInt("duration_seconds"),
                    completedAt
            );
        }
    }

    private static class PlayerStatsRowMapper implements RowMapper<PlayerStats> {
        @Override
        public PlayerStats mapRow(ResultSet rs, int rowNum) throws SQLException {
            Timestamp ts = rs.getTimestamp("last_played_at");
            LocalDateTime lastPlayed = ts != null ? ts.toLocalDateTime() : null;

            return new PlayerStats(
                    rs.getString("username"),
                    rs.getInt("matches_played"),
                    rs.getInt("wins"),
                    rs.getInt("losses"),
                    rs.getInt("kills"),
                    rs.getInt("deaths"),
                    rs.getInt("score"),
                    lastPlayed
            );
        }
    }
}
